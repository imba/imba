// Phase 3 — LLM-facing reference, generated from the verified JSON so it can
// never drift from ground truth. Renders concept -> rule -> VERIFIED example ->
// counterexample, which is the shape that actually reduces model errors.
//
// Pure builder: exports renderMarkdown(reference, corpus). css-docs.mjs writes it.

const fence = (lang, body) => '```' + lang + '\n' + body + '\n```'

// The css_actual strings wrap declarations in `.scope-af { ... }`. Keep them
// verbatim — the scope class is itself instructive — but trim trailing space.
const tidy = (s) => String(s == null ? '' : s).replace(/[ \t]+$/gm, '').trim()

function aliasRows(aliases) {
	const rows = Object.entries(aliases).map(([short, def]) => {
		const css = Array.isArray(def.css) ? def.css.join(' + ') : def.css
		return `| \`${short}\` | \`${css}\`${def.virtual ? ' *' : ''} |`
	})
	return rows.join('\n')
}

function layoutRows(layouts) {
	return Object.entries(layouts).map(([name, def]) => {
		const css = Object.entries(def.css || {}).map(([k, v]) => `${k}:${v}`).join('; ')
		return `| \`d:${name}\` | ${css} |`
	}).join('\n')
}

function ruleSection(rule, corpusByRule) {
	const lines = [`#### \`${rule.id}\` — ${rule.applies_to}`, '', rule.description, '']
	if (rule.source) lines.push(`Source: \`${rule.source}\``, '')
	// Prefer the verified corpus example(s) for this rule; fall back to rule.examples.
	const verified = (rule.examples || []).filter((e) => e.css_actual)
	for (const ex of verified) {
		const out = ex.css_actual.startsWith('ERROR:') ? ex.css_actual : tidy(ex.css_actual)
		lines.push(fence('imba', `css ${ex.imba.replace(/\n/g, '\n    ')}`))
		lines.push('→ compiled CSS (verified):')
		lines.push(fence('css', out), '')
	}
	return lines.join('\n')
}

function modifierSection(m) {
	const shim = m.pseudo_classes.filter((p) => p.shimmable).map((p) => `\`@${p.name}\``).join(', ')
	const plain = m.pseudo_classes.filter((p) => !p.shimmable).map((p) => `\`@${p.name}\``).join(', ')
	const bps = Object.entries(m.breakpoints).map(([k, v]) => `| \`@${k}\` | ${v.media}${v.negated ? ` (neg: ${v.negated})` : ''} |`).join('\n')
	const media = Object.keys(m.media).map((k) => `\`@${k}\``).join(', ')
	const flags = Object.keys(m.flags).map((k) => `\`@${k}\``).join(', ')
	const pri = Object.entries(m.priority).map(([k, v]) => `\`@${k}\` (${v.priority})`).join(', ')
	return [
		'### Modifiers',
		'',
		'Modifiers attach **inline after a value**: `css bg:blue5 @hover:blue6`.',
		'',
		`**Shimmable pseudo-classes** (compile to \`:is(:x, .\\@x)\` so flags can toggle them): ${shim}`,
		'',
		`**Other pseudo-classes:** ${plain}`,
		'',
		`**Pseudo-elements:** ${m.pseudo_elements.map((e) => `\`@${e}\``).join(', ')}`,
		'',
		'**Breakpoints:**',
		'',
		'| Modifier | Media |',
		'|---|---|',
		bps,
		'',
		`**Media/feature:** ${media}`,
		'',
		`**Runtime state flags** (class selectors toggled by Imba): ${flags}`,
		'',
		`**Priority:** ${pri}`,
		'',
		m.note,
	].join('\n')
}

function gotchaSection(corpus) {
	const gotchas = corpus.entries.filter((e) => e.cat === 'gotcha')
	const parts = ['### Gotchas (verified counterexamples)', '']
	for (const g of gotchas) {
		parts.push(`**\`${g.imba.replace(/\n/g, ' / ')}\`** — ${g.note || ''}`)
		parts.push('')
		if (g.error) {
			parts.push(fence('text', `compile error: ${g.error}`))
		} else {
			parts.push(fence('css', tidy(g.css)))
		}
		parts.push('')
	}
	return parts.join('\n')
}

function tokenSection(t) {
	const fsNamed = Object.entries(t.font_size.named).map(([k, v]) => `\`${k}\`=${v.size}`).join(', ')
	const easings = Object.keys(t.easings || {}).join(', ')
	return [
		'### Tokens',
		'',
		`**Color families** (shades ${t.colors.shades}): ${t.colors.families.map((c) => `\`${c}\``).join(', ')}`,
		'',
		`Alpha: \`${t.colors.alpha}\`. Fractional: \`${t.colors.fractional}\`. Specials: ${t.colors.specials.map((s) => `\`${s}\``).join(', ')}. Plus ${Object.keys(t.colors.named).length} CSS named colors.`,
		'',
		`**Font stacks:** ${Object.keys(t.font_family).map((f) => `\`${f}\``).join(', ')}`,
		'',
		`**Named font sizes:** ${fsNamed} (numeric \`1\`–\`16\` also available)`,
		'',
		`**Radius:** ${Object.entries(t.radius).map(([k, v]) => `\`${k}\`=${v}`).join(', ')}`,
		'',
		`**Box-shadow scale:** ${t.box_shadow.map((s) => `\`${s}\``).join(', ')}`,
		'',
		`**Easings:** ${easings}`,
	].join('\n')
}

export function renderMarkdown(reference, corpus) {
	const { aliases, layouts, keyword_values, tokens, rules, modifiers, mechanisms } = reference
	const kw = Object.entries(keyword_values).map(([prop, def]) =>
		`- \`${prop}\`: ${Object.entries(def.values).map(([k, v]) => `\`${k}\`→\`${v}\``).join(', ')}`).join('\n')

	return [
		'<!-- GENERATED by scripts/docs/css-docs.mjs — do not edit by hand.',
		'     Regenerate: `npm run docs:css`. CI guard: `npm run docs:css:check`. -->',
		'# Imba CSS Reference (generated)',
		'',
		'Machine-verified ground truth for Imba CSS shorthands. Property aliases, layouts,',
		'tokens and modifiers are extracted from the compiler source; every rule example',
		'below is captured by **actually compiling** the snippet (scope hash normalized to',
		'`.scope`). For concepts and idioms see the hand-written `css-system.md`.',
		'',
		'## Property aliases',
		'',
		'`*` marks a virtual target that the compiler expands further (e.g. `padding-x`, `size`).',
		'',
		'| Short | CSS property |',
		'|---|---|',
		aliasRows(aliases),
		'',
		'## Compound display layouts (`d:`)',
		'',
		'| Value | Expands to |',
		'|---|---|',
		layoutRows(layouts),
		'',
		'## Keyword value expansions',
		'',
		kw,
		'',
		'## Algorithmic rules',
		'',
		'These transform values by a rule — they cannot be enumerated. Each shows a',
		'compiler-verified input→output pair.',
		'',
		rules.map((r) => ruleSection(r)).join('\n'),
		tokenSection(tokens),
		'',
		modifierSection(modifiers),
		'',
		'### DOM / runtime mechanisms',
		'',
		'The real "DOM impact" is this small fixed set — not a per-property fact:',
		'',
		mechanisms.map((m) => `- **${m.id}** — ${m.summary}`).join('\n'),
		'',
		gotchaSection(corpus),
	].join('\n') + '\n'
}
